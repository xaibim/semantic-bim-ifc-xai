from __future__ import annotations

import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def normalized_text(path: Path) -> str:
    return " ".join(read_text(path).split())


def lower_text(path: Path) -> str:
    return read_text(path).lower()


class TestPlannedBenchmarkProtocol(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.execution = read_text(ROOT / "benchmark" / "benchmark_execution_protocol.md")
        cls.sap = read_text(ROOT / "benchmark" / "statistical_analysis_plan.md")
        cls.governance = read_text(ROOT / "docs" / "methodology" / "dataset_governance_split_and_leakage_protocol.md")
        cls.readme = read_text(ROOT / "README.md")
        cls.baseline_matrix = read_text(ROOT / "benchmark" / "baseline_matrix.md")
        cls.validation_gates = read_text(ROOT / "docs" / "methodology" / "validation_gates.md")

    def test_01_required_documents_exist(self) -> None:
        for rel in [
            "benchmark/benchmark_execution_protocol.md",
            "benchmark/statistical_analysis_plan.md",
            "docs/methodology/dataset_governance_split_and_leakage_protocol.md",
        ]:
            with self.subTest(path=rel):
                self.assertTrue((ROOT / rel).exists())

    def test_02_readme_links(self) -> None:
        text = self.readme
        for link in [
            "benchmark/benchmark_execution_protocol.md",
            "benchmark/statistical_analysis_plan.md",
            "docs/methodology/dataset_governance_split_and_leakage_protocol.md",
            "benchmark/baseline_matrix.md",
        ]:
            with self.subTest(link=link):
                self.assertIn(link, text)

    def test_03_baseline_matrix_links(self) -> None:
        text = self.baseline_matrix
        for link in [
            "benchmark_execution_protocol.md",
            "statistical_analysis_plan.md",
            "../docs/methodology/dataset_governance_split_and_leakage_protocol.md",
        ]:
            with self.subTest(link=link):
                self.assertIn(link, text)

    def test_04_status_and_boundary_markers(self) -> None:
        for text in [self.execution, self.sap, self.governance]:
            self.assertIn("PLANNED_NOT_EXECUTED", text)
        self.assertIn("NOT_A_COMPARATIVE_BENCHMARK", self.execution)
        self.assertIn("NO_COMPARATIVE_INFERENCE_HAS_BEEN_PERFORMED", self.sap)
        self.assertIn("CURRENT_SAMPLE20_SCOPE = MINIMAL_PUBLIC_FIXTURE_ONLY", self.governance)

    def test_05_no_comparative_results_or_score_tables(self) -> None:
        execution = normalized_text(ROOT / "benchmark" / "benchmark_execution_protocol.md").lower()
        for text in [self.sap.lower(), self.governance.lower()]:
            self.assertNotIn("score table", text)
            self.assertNotIn("fabricated result", text)
        self.assertIn("does not contain comparative results", execution)
        self.assertIn("does not report comparative benchmark results", execution)
        self.assertNotIn("score table", execution)
        self.assertNotIn("fabricated result", execution)

    def test_06_sample20_fixture_boundary(self) -> None:
        execution = normalized_text(ROOT / "benchmark" / "benchmark_execution_protocol.md").lower()
        self.assertIn("sample20", execution)
        self.assertIn("minimal reproducibility fixture", execution)
        self.assertIn("not a comparative benchmark", execution)
        self.assertIn("minimal_public_fixture_only", self.governance.lower())

    def test_07_dataset_identity_and_grouping(self) -> None:
        governance = normalized_text(ROOT / "docs" / "methodology" / "dataset_governance_split_and_leakage_protocol.md").lower()
        for phrase in [
            "record_id",
            "root_case_id",
            "variant_id",
            "source_record_id",
            "no `root_case_id` may cross train, validation, test or evaluation splits",
            "splits must be generated by groups, not by individual records",
        ]:
            self.assertIn(phrase, governance)

    def test_08_duplicate_and_leakage_controls(self) -> None:
        text = self.governance.lower()
        for phrase in [
            "exact byte/content hash",
            "normalized exact duplicate",
            "semantic or near duplicate",
            "retrieval corpus must have its own version and hash",
            "leakage must be separated across",
            "few-shot examples",
            "prompts or tools",
        ]:
            self.assertIn(phrase, text)

    def test_09_evidence_and_disclosure_levels(self) -> None:
        for phrase in [
            "e0 — trace_present",
            "e1 — reference_resolvable",
            "e2 — claim_supported",
            "e3 — professionally_sufficient",
            "cannot always be proven",
            "must not be described as contamination-free",
        ]:
            self.assertIn(phrase, self.governance.lower())

    def test_10_baseline_statuses(self) -> None:
        text = self.execution
        for phrase in [
            "A - Deterministic IFC/schema/catalogue lookup - REQUIRED",
            "B - Base LLM, prompt-only - REQUIRED",
            "C - Base LLM with retrieved IFC/bSDD/IDS context - REQUIRED",
            "D - Graph or ontology-grounded retrieval - CONDITIONAL",
            "E - Tool-using adaptive IFC exploration - CONDITIONAL",
            "F - Single-agent planner - OPTIONAL",
            "G - Multi-agent workflow - OPTIONAL",
            "H - QLoRA-adapted model - OPTIONAL_AFTER_GATES",
        ]:
            self.assertIn(phrase, text)

    def test_11_execution_and_metric_rules(self) -> None:
        text = self.execution.lower()
        for phrase in [
            "same evaluation set",
            "frozen retrieval corpus",
            "same evaluator and metric version",
            "failed outputs",
            "wall-clock time",
            "cpu core.hours",
            "gpu.hours",
            "peak ram",
            "peak vram",
            "storage footprint",
            "grounding and supportedness require future resolvable references",
        ]:
            self.assertIn(phrase, text)

    def test_12_statistical_plan_rules(self) -> None:
        text = normalized_text(ROOT / "benchmark" / "statistical_analysis_plan.md").lower()
        for phrase in [
            "paired on the same cases",
            "clustered bootstrap resampling by `root_case_id`",
            "to_be_frozen",
            "holm",
            "95% bilateral confidence intervals",
            "seed-level outputs as independent cases",
            "no statistical inference is executed on `sample20`",
            "do not claim general aeco superiority",
        ]:
            self.assertIn(phrase, text)

    def test_13_no_specific_funding_program_tokens(self) -> None:
        text = " ".join([self.execution, self.sap, self.governance, self.readme, self.baseline_matrix, self.validation_gates]).lower()
        for token in [
            "grant program",
            "funding call",
            "call for proposals",
            "application form",
        ]:
            self.assertNotIn(token, text)

    def test_14_no_superiority_or_fabricated_results(self) -> None:
        text = " ".join([
            normalized_text(ROOT / "benchmark" / "benchmark_execution_protocol.md"),
            normalized_text(ROOT / "benchmark" / "statistical_analysis_plan.md"),
            normalized_text(ROOT / "docs" / "methodology" / "dataset_governance_split_and_leakage_protocol.md"),
            normalized_text(ROOT / "README.md"),
        ]).lower()
        for phrase in [
            "is superior to",
            "outperforms",
            "winning model",
            "best model",
        ]:
            self.assertNotIn(phrase, text)
        self.assertNotIn("fabricated result", text)

    def test_15_layer_c_gates(self) -> None:
        text = self.validation_gates
        for gate in ["G0", "G1", "G2", "G3", "G4", "G5", "G6", "G7", "G8"]:
            with self.subTest(gate=gate):
                self.assertIn(gate, text)
        for phrase in [
            "planned comparative benchmark gates",
            "planned_not_executed",
        ]:
            self.assertIn(phrase.lower(), text.lower())


if __name__ == "__main__":
    unittest.main()
